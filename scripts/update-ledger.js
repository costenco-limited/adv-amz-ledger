#!/usr/bin/env node
// Refreshes the ledger's data (data.js) from Amazon SP-API and Keepa.
// Runs on GitHub Actions every few hours (.github/workflows/update-ledger.yml).
//
// Recomputes the last WINDOW_DAYS days of sales, refunds and fees, the current stock,
// the monthly per-SKU table for months the cache fully covers, and the stalest Keepa ranks.
// Older days are left exactly as they are.
//
// Needs AMAZON_CLIENT_ID, AMAZON_CLIENT_SECRET, AMAZON_REFRESH_TOKEN and (optional) KEEPA_API_KEY.

const fs = require('fs');
const path = require('path');
const axios = require('axios');
const { MARKETPLACES, CHANNELS, call, report, parseTsv, sleep } = require('./lib/spapi');
const { financialEventsByDay, amount } = require('./lib/finances');
const { loadRates } = require('./lib/fx');

const ROOT = path.join(__dirname, '..');
const DATA_FILE = path.join(ROOT, 'data.js');
const STATE_FILE = path.join(ROOT, 'data', 'state.json');
const COSTS_FILE = path.join(ROOT, 'data', 'costs.json');

const WINDOW_DAYS = 30;     // days of sales/refunds/fees recomputed each run
const FEE_RATE_DAYS = 60;   // fee per unit comes from this many days of settlements
const SKU_CACHE_DAYS = 70;  // per-SKU daily history kept for the monthly table
const TZ = 'Europe/Berlin'; // the ledger's days run on CET/CEST
const DATA_NAMES = ['META', 'DAYS', 'INV', 'THUMBS', 'MONTHLY_SALES', 'KEEPA'];

// Standard VAT by destination country (sales are VAT-inclusive)
const VAT = {
  AT: .20, BE: .21, BG: .20, HR: .25, CY: .19, CZ: .21, DK: .25, EE: .24, FI: .255, FR: .20, DE: .19,
  GR: .24, HU: .27, IE: .23, IT: .22, LV: .21, LT: .21, LU: .17, MT: .18, NL: .21, PL: .23, PT: .23,
  RO: .21, SK: .23, SI: .22, ES: .21, SE: .25, GB: .20, AE: .05, SA: .15, MC: .20
};
const MARKET_COUNTRY = { DE: 'DE', UK: 'GB', FR: 'FR', ES: 'ES', IT: 'IT', AE: 'AE', NL: 'NL', SA: 'SA', SE: 'SE', PL: 'PL', BE: 'BE', IE: 'IE' };
// Marketplace whose FBA inventory represents each stock pool
const POOLS = { EU: 'IT', UK: 'UK', AE: 'AE', SA: 'SA' };
const KEEPA_DOMAINS = { DE: 3, FR: 4, IT: 8, ES: 9 };

// ---------- dates (YYYY-MM-DD strings in CET)
const cetDay = d => new Date(d).toLocaleDateString('sv-SE', { timeZone: TZ });
const addDays = (day, n) => { const d = new Date(day + 'T12:00:00Z'); d.setUTCDate(d.getUTCDate() + n); return d.toISOString().slice(0, 10); };
// UTC instant of 00:00 CET/CEST on `day`
function cetMidnight(day) {
  const guess = new Date(day + 'T00:00:00Z');
  const local = new Date(guess.toLocaleString('en-US', { timeZone: TZ }));
  return new Date(guess.getTime() - (local.getTime() - guess.getTime()));
}
const iso = d => d.toISOString().replace(/\.\d{3}Z$/, 'Z');
const round2 = n => Math.round(n * 100) / 100;
const log = (...a) => console.log(new Date().toISOString().slice(11, 19), ...a);

// ---------- data.js
function readData() {
  const text = fs.readFileSync(DATA_FILE, 'utf8');
  const data = {};
  for (const name of DATA_NAMES) {
    const m = text.match(new RegExp(`^const ${name} = (.*);$`, 'm'));
    if (!m) throw new Error(`data.js has no ${name}`);
    data[name] = JSON.parse(m[1]);
  }
  return data;
}
function writeData(data) {
  const text = '// Generated by scripts/update-ledger.js — do not edit by hand.\n'
    + DATA_NAMES.map(n => `const ${n} = ${JSON.stringify(data[n])};`).join('\n') + '\n';
  fs.writeFileSync(DATA_FILE, text);
}
const readJson = (file, fallback) => fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : fallback;

// ---------- sales from the orders report
async function loadOrders(fromDay, until) {
  const text = await report('GET_FLAT_FILE_ALL_ORDERS_DATA_BY_ORDER_DATE_GENERAL', Object.values(MARKETPLACES), {
    start: iso(cetMidnight(fromDay)), end: iso(until)
  });
  // Rows hold buyer addresses: keep only what the ledger needs, never write rows to disk
  return (text ? parseTsv(text) : []).map(r => ({
    order: r['amazon-order-id'],
    status: r['order-status'],
    mkt: CHANNELS[r['sales-channel']],
    day: cetDay(r['purchase-date']),
    sku: r.sku,
    asin: r.asin,
    units: parseFloat(r.quantity) || 0,
    price: r['item-price'] === '' ? null : parseFloat(r['item-price']) || 0,
    currency: r.currency,
    country: r['ship-country']
  })).filter(r => r.mkt && r.status !== 'Cancelled');
}

// Per (day, market): orders, units, VAT-inclusive sales in EUR, VAT, pending units, and per-SKU units/sales.
// Pending items have no price yet, so they're valued at the SKU's recent average price.
function aggregateOrders(rows, rate) {
  const unitPrice = {}; // sku|mkt and sku -> [eur, units]
  for (const r of rows) {
    if (r.price == null || !r.units) continue;
    const eur = r.price / rate(r.day, r.currency);
    for (const k of [`${r.sku}|${r.mkt}`, r.sku, `*|${r.mkt}`]) {
      const p = unitPrice[k] ??= [0, 0];
      p[0] += eur; p[1] += r.units;
    }
  }
  const priceOf = (sku, mkt) => {
    for (const k of [`${sku}|${mkt}`, sku, `*|${mkt}`]) if (unitPrice[k]?.[1]) return unitPrice[k][0] / unitPrice[k][1];
    return 0;
  };

  const days = {};
  const skuDays = {};
  for (const r of rows) {
    const pending = r.price == null || r.status === 'Pending';
    const eur = r.price != null ? r.price / rate(r.day, r.currency) : r.units * priceOf(r.sku, r.mkt);
    const vatRate = VAT[r.country] ?? VAT[MARKET_COUNTRY[r.mkt]] ?? 0;
    const d = (days[r.day] ??= {})[r.mkt] ??= { orders: new Set(), units: 0, sales: 0, vat: 0, pending: 0, skus: {} };
    d.orders.add(r.order);
    d.units += r.units;
    d.sales += eur;
    d.vat += eur * vatRate / (1 + vatRate);
    if (pending) d.pending += r.units;
    d.skus[r.sku] = (d.skus[r.sku] || 0) + r.units;
    const s = ((skuDays[r.day] ??= {})[r.mkt] ??= {})[r.sku] ??= [0, 0];
    s[0] += r.units; s[1] = round2(s[1] + eur);
  }
  return { days, skuDays };
}

// ---------- fees, refunds and account charges from financial events
// `byDay` holds each CET day's events (fetched one day at a time), so every event is
// dated by its fetch window, including account charges that carry no PostedDate.
function aggregateFinances(byDay, rate) {
  const feeDays = {};   // day -> "sku|mkt" -> [units, feeEUR]
  const refunds = {};   // day -> mkt -> [units, costEUR]
  const other = {};     // day -> EUR (account-level charges)

  for (const [day, ev] of Object.entries(byDay)) {
    const eur = m => amount(m) / rate(day, m?.CurrencyCode);

    for (const e of ev.ShipmentEventList || []) {
      const mkt = CHANNELS[e.MarketplaceName];
      if (!mkt) continue;
      for (const it of e.ShipmentItemList || []) {
        const fee = -(it.ItemFeeList || []).reduce((a, f) => a + eur(f.FeeAmount), 0);
        const f = (feeDays[day] ??= {})[`${it.SellerSKU}|${mkt}`] ??= [0, 0];
        f[0] += it.QuantityShipped || 0;
        f[1] = round2(f[1] + fee);
      }
    }
    for (const e of ev.RefundEventList || []) {
      const mkt = CHANNELS[e.MarketplaceName];
      if (!mkt) continue;
      const r = (refunds[day] ??= {})[mkt] ??= [0, 0];
      for (const it of e.ShipmentItemAdjustmentList || []) {
        r[0] += it.QuantityShipped || 0;
        r[1] += refundCost(it, eur);
      }
    }
    for (const value of accountCharges(ev, eur)) other[day] = (other[day] || 0) + value;
  }
  return { feeDays, refunds, other };
}

// Money lost on a refunded item: everything refunded to the buyer (incl. VAT and promotions)
// less the fees Amazon gives back
function refundCost(item, eur) {
  let cost = 0;
  for (const c of item.ItemChargeAdjustmentList || []) cost -= eur(c.ChargeAmount);
  for (const f of item.ItemFeeAdjustmentList || []) cost -= eur(f.FeeAmount);
  for (const p of item.PromotionAdjustmentList || []) cost -= eur(p.PromotionAmount);
  return cost;
}

// Account-level charges not tied to an order line (storage, subscription, removals...),
// less reimbursements and other adjustments in the seller's favour
function* accountCharges(ev, eur) {
  for (const e of ev.ServiceFeeEventList || []) for (const f of e.FeeList || []) yield -eur(f.FeeAmount);
  for (const e of ev.AdjustmentEventList || []) yield -eur(e.AdjustmentAmount);
}

// ---------- stock
async function loadInventory(prevInv, watchlist) {
  const prev = Object.fromEntries(prevInv.map(r => [`${r.pool}|${r.sku}`, r]));
  const listEan = Object.fromEntries(watchlist.products.filter(p => p.ean).map(p => [p.asin, p.ean]));
  const rows = [];
  for (const [pool, mkt] of Object.entries(POOLS)) {
    const id = MARKETPLACES[mkt];
    let nextToken = null;
    do {
      const q = `granularityType=Marketplace&granularityId=${id}&marketplaceIds=${id}&details=true` + (nextToken ? `&nextToken=${encodeURIComponent(nextToken)}` : '');
      const data = await call('get', `/fba/inventory/v1/summaries?${q}`);
      for (const s of data.payload?.inventorySummaries || []) {
        const d = s.inventoryDetails || {};
        const available = d.fulfillableQuantity || 0;
        const reserved = d.reservedQuantity?.totalReservedQuantity || 0;
        const unfulfillable = d.unfulfillableQuantity?.totalUnfulfillableQuantity || 0;
        const researching = d.researchingQuantity?.totalResearchingQuantity || 0;
        const inbound = (d.inboundWorkingQuantity || 0) + (d.inboundShippedQuantity || 0) + (d.inboundReceivingQuantity || 0);
        const inFC = available + reserved + unfulfillable + researching;
        if (!inFC && !inbound) continue;
        const old = prev[`${pool}|${s.sellerSku}`];
        const ean = old?.ean || listEan[s.asin] || '';
        rows.push({
          pool, asin: s.asin, sku: s.sellerSku, title: s.productName || old?.title || s.sellerSku, en: true,
          ean, eanSrc: old?.ean ? old.eanSrc : ean ? 'list' : '',
          inFC, available, reserved, unfulfillable, researching, inbound
        });
      }
      nextToken = data.pagination?.nextToken;
      if (nextToken) await sleep(600);
    } while (nextToken);
    log(`stock ${pool}: ${rows.filter(r => r.pool === pool).length} products`);
  }
  return rows.sort((a, b) => b.inFC - a.inFC || b.inbound - a.inbound);
}

// ---------- Keepa sales ranks (refreshes the stalest cells the token balance allows)
async function refreshKeepa(keepa, asins, state) {
  const key = process.env.KEEPA_API_KEY;
  if (!key) { log('keepa: no KEEPA_API_KEY, skipped'); return; }
  const fetched = state.keepaFetched ??= {};
  const { data: tok } = await axios.get(`https://api.keepa.com/token?key=${key}`);
  let budget = (tok.tokensLeft || 0) - 5;
  const cells = [];
  for (const mkt of Object.keys(KEEPA_DOMAINS)) for (const asin of asins) cells.push([asin, mkt, fetched[`${asin}|${mkt}`] || '']);
  cells.sort((a, b) => a[2].localeCompare(b[2]));
  const todo = {};
  for (const [asin, mkt] of cells) { if (budget-- <= 0) break; (todo[mkt] ??= []).push(asin); }

  let done = 0;
  for (const [mkt, list] of Object.entries(todo)) {
    for (let i = 0; i < list.length; i += 100) {
      const batch = list.slice(i, i + 100);
      const { data } = await axios.get('https://api.keepa.com/product', {
        params: { key, domain: KEEPA_DOMAINS[mkt], asin: batch.join(','), stats: 1 }, timeout: 120000
      });
      for (const p of data.products || []) {
        const bsr = p.stats?.current?.[3];
        (keepa[p.asin] ??= {})[mkt] = {
          bsr: bsr > 0 ? bsr : null,
          est_sales_30d: p.monthlySold > 0 ? p.monthlySold : null,
          has_buybox: keepa[p.asin]?.[mkt]?.has_buybox ?? null
        };
        fetched[`${p.asin}|${mkt}`] = new Date().toISOString();
        done++;
      }
    }
  }
  log(`keepa: refreshed ${done} ranks (${cells.length} total, ${tok.tokensLeft} tokens available)`);
}

// ---------- main
async function main() {
  const now = new Date();
  const today = process.env.LEDGER_TODAY || cetDay(now); // LEDGER_TODAY: test against a past day
  const until = process.env.LEDGER_TODAY ? cetMidnight(addDays(today, 1)) : new Date(now.getTime() - 3 * 60 * 1000);
  const from = addDays(today, -(WINDOW_DAYS - 1));
  log(`updating ${from} .. ${today}`);

  const data = readData();
  const state = readJson(STATE_FILE, {});
  const costs = readJson(COSTS_FILE, {});
  const watchlist = require(path.join(ROOT, 'watchlist.json'));
  const rate = await loadRates(addDays(from, -FEE_RATE_DAYS - 5), today);

  // Sales
  const orders = await loadOrders(from, until);
  log(`orders: ${orders.length} order lines`);
  const { days, skuDays } = aggregateOrders(orders, rate);

  // Fees and refunds, one CET day at a time (first run also fills the fee-rate history)
  const finFrom = state.feeDays ? from : addDays(today, -(FEE_RATE_DAYS - 1));
  const windows = [];
  for (let day = finFrom; day <= today; day = addDays(day, 1)) {
    const end = new Date(Math.min(cetMidnight(addDays(day, 1)), until));
    if (end > cetMidnight(day)) windows.push([day, iso(cetMidnight(day)), iso(end)]);
  }
  const byDay = await financialEventsByDay(windows);
  const fin = aggregateFinances(byDay, rate);
  log(`financial events: ${windows.length} days from ${finFrom}`);

  // Fee per unit by SKU and market over the last FEE_RATE_DAYS of settlements
  state.feeDays = { ...(state.feeDays || {}), ...fin.feeDays };
  for (const day of Object.keys(state.feeDays)) if (day < addDays(today, -FEE_RATE_DAYS)) delete state.feeDays[day];
  const feeTotals = {};
  for (const perKey of Object.values(state.feeDays)) {
    for (const [key, [u, f]] of Object.entries(perKey)) {
      const [sku, mkt] = key.split('|');
      for (const k of [key, sku, `*|${mkt}`]) { const t = feeTotals[k] ??= [0, 0]; t[0] += u; t[1] += f; }
    }
  }
  const feeRate = (sku, mkt) => {
    for (const k of [`${sku}|${mkt}`, sku, `*|${mkt}`]) if (feeTotals[k]?.[0]) return feeTotals[k][1] / feeTotals[k][0];
    return 0;
  };

  // Product cost: data/costs.json, else the watchlist cost for the ASIN
  const skuAsin = Object.fromEntries(orders.map(r => [r.sku, r.asin]));
  const listCost = Object.fromEntries(watchlist.products.filter(p => p.cost).map(p => [p.asin, p.cost]));
  let missingCostUnits = 0;
  const costOf = (sku, units) => {
    const c = costs[sku]?.cost ?? listCost[skuAsin[sku]];
    if (c == null) { missingCostUnits += units; return 0; }
    return c;
  };

  // Rebuild DAYS for the window
  for (let day = from; day <= today; day = addDays(day, 1)) {
    const out = {};
    const markets = new Set([...Object.keys(days[day] || {}), ...Object.keys(fin.refunds[day] || {})]);
    for (const mkt of markets) {
      const d = days[day]?.[mkt];
      const r = fin.refunds[day]?.[mkt] || [0, 0];
      let fee = 0, cogs = 0;
      for (const [sku, u] of Object.entries(d?.skus || {})) { fee += u * feeRate(sku, mkt); cogs += u * costOf(sku, u); }
      out[mkt] = [d?.orders.size || 0, d?.units || 0, round2(d?.sales || 0), round2(d?.vat || 0), round2(fee), round2(cogs),
        d?.pending || 0, r[0], round2(r[1])];
    }
    if (fin.other[day]) out._ = round2(fin.other[day]);
    if (Object.keys(out).length) data.DAYS[day] = out; else delete data.DAYS[day];
  }

  // Monthly per-SKU table, for every month the per-SKU cache covers completely
  state.skuDays = { ...(state.skuDays || {}), ...skuDays };
  for (let day = from; day <= today; day = addDays(day, 1)) if (!skuDays[day]) state.skuDays[day] = {};
  for (const day of Object.keys(state.skuDays)) if (day < addDays(today, -SKU_CACHE_DAYS)) delete state.skuDays[day];
  const months = [...new Set(Object.keys(state.skuDays).map(d => d.slice(0, 7)))];
  for (const month of months) {
    const first = month + '-01';
    if (!(first in state.skuDays)) continue; // month starts before the cache
    const table = {};
    for (const [day, perMkt] of Object.entries(state.skuDays)) {
      if (!day.startsWith(month)) continue;
      for (const [mkt, perSku] of Object.entries(perMkt)) {
        for (const [sku, [u, eur]] of Object.entries(perSku)) {
          const cell = (table[mkt] ??= {})[`${sku}|${mkt}`] ??= [0, 0, 0];
          cell[0] += u; cell[1] = round2(cell[1] + eur);
        }
      }
    }
    for (const perMkt of Object.values(table)) for (const cell of Object.values(perMkt)) cell[2] = cell[0] ? round2(cell[1] / cell[0]) : 0;
    data.MONTHLY_SALES.months[month] = table;
  }

  // Stock
  data.INV = await loadInventory(data.INV, watchlist);

  // Keepa
  try {
    await refreshKeepa(data.KEEPA, watchlist.products.map(p => p.asin), state);
  } catch (err) {
    log('keepa failed (keeping previous ranks):', err.message);
  }
  data.MONTHLY_SALES.keepa = data.KEEPA;

  // Meta
  const stamp = new Date(Math.min(now, until));
  data.META.today = today;
  data.META.asOf = stamp.toLocaleString('en-GB', { timeZone: TZ, day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' }).replace(' at', ',');
  data.META.invAsOf = stamp.toLocaleString('sv-SE', { timeZone: TZ }).slice(0, 16);
  data.META.missingCostUnits = missingCostUnits;
  data.MONTHLY_SALES.asOf = stamp.toISOString();

  writeData(data);
  fs.mkdirSync(path.dirname(STATE_FILE), { recursive: true });
  fs.writeFileSync(STATE_FILE, JSON.stringify(state));
  log(`done; ${missingCostUnits} units without a product cost`);
}

if (require.main === module) {
  main().catch(err => { console.error(err.stack || err.message); process.exit(1); });
}

module.exports = { aggregateOrders, aggregateFinances, cetDay, cetMidnight, addDays, VAT };
